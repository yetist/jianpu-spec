def parse_note(tok):
    el = NoteEl()
    i = 0
    n = len(tok)
    while i < n:
        c = tok[i]
        if c == "(":
            el.opens += 1
            if i + 1 < n and tok[i + 1] == "y":
                el.multi = True
                i += 1
        elif c == ")":
            el.closes += 1
        elif c == "[":
            j = tok.find("]", i)
            if j < 0:
                j = n - 1
            grp = tok[i:j + 1]
            if grp[1:2] == "h":
                el.grace_back.append(parse_graces(grp[2:-1]))
            else:
                el.grace_front.append(parse_graces(grp[1:-1]))
            i = j
        elif c == '"':
            j = tok.find('"', i + 1)
            if j < 0:
                j = n
            el.text = tok[i + 1:j]
            i = j
        elif c == "&":
            k = i + 1
            while k < n and tok[k].isalnum():
                k += 1
            el.marks.append(tok[i + 1:k])
            i = k - 1
        elif c in "<>":
            k = i + 1
            while k < n and tok[k] == "+":
                k += 1
            el.cresc = (c, k - (i + 1))
            i = k - 1
        elif c == "!":
            el.cresc_end = True
        elif c == "/":
            el.slashes += 1
        elif c == ".":
            el.dots += 1
        elif c == ",":
            el.octave -= 1
        elif c == "'":
            el.octave += 1
        elif c in "#$=":
            el.acc = c
        elif c == "~":
            el.beat_join = True
        elif c == "^":
            el.beat_up = True
        elif c.isdigit() or c == "-":
            if el.pitch is None:
                el.pitch = c
        i += 1
    return el


def parse_bar(tok):
    el = BarEl()
    i = 0
    n = len(tok)
    last_bracket = False
    while i < n:
        c = tok[i]
        if c == "(":
            el.opens += 1
        elif c == ")":
            el.closes += 1
        elif c == "|":
            el.lines += 1
        elif c == ":":
            if i > 0 and tok[i - 1] == "|":
                el.left_rep = True
            else:
                el.right_rep = True
        elif c == "/":
            if last_bracket:
                el.house_unclosed = True
            elif el.lines == 1:
                el.hide = True
        elif c == "*":
            el.hide = True
            el.hide_space = True
        elif c == "&":
            k = i + 1
            while k < n and tok[k].isalpha():
                k += 1
            tag = tok[i + 1:k]
            if tag == "sbf":
                el.sbf = True
            elif tag:
                el.tags.append(tag)
            i = k - 1
        elif c == "[":
            el.house_open = True
        elif c == "]":
            el.house_close = True
            last_bracket = True
        elif c == "+":
            el.plus += 1
        elif c == '"':
            k = tok.find('"', i + 1)
            if k < 0:
                k = n
            content = tok[i + 1:k]
            if content.startswith("p:"):
                el.pai = content[2:]
            else:
                el.house_text = content
            i = k
        i += 1
    return el


def parse_key(val):
    acc = ""
    letter = ""
    for ch in val:
        if ch in "#$":
            acc = ch
        elif ch.isalpha():
            letter = ch
    return letter.upper(), acc


def parse_pai(val):
    val = val.strip()
    m = re.match(r"^(\d+\s*/\s*\d+)\s*(.*)$", val)
    if not m:
        return val, ""
    main = m.group(1).replace(" ", "")
    rest = m.group(2).strip().strip("()").strip()
    return main, rest


def parse_block(tok):
    """解析 {bz ...} / {dsb ...} 临时伴奏/多声部块, 返回 (类型, 元素列表)。"""
    body = tok[1:-1] if tok.endswith("}") else tok[1:]
    body = body.strip()
    kind = ""
    for prefix in ("bz", "dsb"):
        if body.startswith(prefix):
            kind = prefix
            body = body[len(prefix):]
            break
    els = []
    for k, t in tokenize(body):
        if k == "bar":
            els.append(parse_bar(t))
        elif k == "note":
            els.append(parse_note(t))
    return kind, merge_elements(els)


def merge_elements(raw):
    """整理元素列表：

    * 丢弃纯记号(无音高)token，把其连音线起止/多连音信息并入相邻音符；
    * 例如 `3 (// 4//)` 中的 `(//` 合并到前一个音符 `3` 上。
    """
    merged = []
    pending_opens = 0
    pending_multi = False
    for el in raw:
        if isinstance(el, NoteEl) and el.pitch is None:
            prev = None
            if (merged and isinstance(merged[-1], NoteEl)
                    and merged[-1].pitch is not None):
                prev = merged[-1]
            if prev is not None:
                # 记号 token 的时值/记号信息归属前一个音符,
                # 例如 `5 (.` => 附点四分音符, `3 (//` => 十六分音符。
                prev.dots += el.dots
                prev.slashes += el.slashes
                if el.acc and not prev.acc:
                    prev.acc = el.acc
                prev.grace_front += el.grace_front
                prev.grace_back += el.grace_back
                prev.marks += el.marks
                if el.text and not prev.text:
                    prev.text = el.text
                prev.opens += el.opens
                prev.multi = prev.multi or el.multi
                prev.closes += el.closes
            else:
                if el.opens:
                    pending_opens += el.opens
                    pending_multi = pending_multi or el.multi
                if el.closes and merged and isinstance(merged[-1], NoteEl):
                    merged[-1].closes += el.closes
            continue
        if isinstance(el, NoteEl) and pending_opens:
            el.opens += pending_opens
            el.multi = el.multi or pending_multi
            pending_opens = 0
            pending_multi = False
        merged.append(el)
    # 增时线 ``-`` 不可能是连音线的端点: ``5 (- -`` 这种把左括弧单独写成
    # 一段的写法, 参考实现把括弧挂在前一个音符上。
    for i, el in enumerate(merged):
        if not (isinstance(el, NoteEl) and el.is_hold):
            continue
        if not (el.opens or el.closes):
            continue
        for j in range(i - 1, -1, -1):
            prev = merged[j]
            if isinstance(prev, NoteEl) and not prev.is_hold:
                prev.opens += el.opens
                prev.multi = prev.multi or el.multi
                prev.closes += el.closes
                el.opens = el.closes = 0
                el.multi = False
                break
    return merged


def _fit_tuplet(seg):
    """把一段连音音符的时值缩到 "不超过原总时值的 2 的幂"。

    参考实现自动计算连音, 3 个八分连音占 1 拍 (每个 1/3 拍), 而不是 1.5 拍。
    """
    total = sum(duration(n) for n in seg)
    if total <= 0:
        return
    target = 1.0
    while target > total + 1e-9:
        target /= 2.0
    while target * 2 <= total + 1e-9:
        target *= 2.0
    if target >= total - 1e-9:
        return
    f = target / total
    for n in seg:
        n.tup *= f
        n.tup_grp = seg


def apply_tuplets(elements):
    """按行处理连音/多连音: 括号内的音符重新分配时值。

    行末还没有右括弧的连音按参考实现的做法收口到本行最后一个音符。
    """
    stack = []
    notes = []
    for el in elements:
        if not isinstance(el, NoteEl):
            continue
        idx = len(notes)
        notes.append(el)
        for _ in range(el.opens):
            stack.append((idx, el))
        for _ in range(el.closes):
            if stack:
                i, a = stack.pop()
                if a.multi and idx > i:
                    _fit_tuplet(notes[i:idx + 1])
    while stack:
        i, a = stack.pop()
        if a.multi and len(notes) - 1 > i:
            _fit_tuplet(notes[i:])


def parse_jps(text):
    """解析脚本, 返回 (Header, items)。

    items 为列表, 每项是 ('system', [QLine...], [LyricLine...], order)
    或 ('pagebreak',)。order 保存声部/歌词在源码中出现的先后次序, 每项为
    ('Q', qline) 或 ('C', lyric), 供渲染时按源顺序纵向排布。
    """
    header = Header()
    items = []
    qgroup = []
    lyrics = []
    order = []
    group_numbered = False          # 当前 system 的声部行是否用的是编号写法

    def flush_group():
        nonlocal qgroup, lyrics, order
        if qgroup:
            items.append(("system", qgroup, lyrics, order))
        qgroup = []
        lyrics = []
        order = []

    prev_kind = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            if qgroup:                      # 空行 => 开始新的 system
                flush_group()
            prev_kind = None
            continue
        if line.startswith("#"):
            continue
        if line == "[fenye]":
            flush_group()
            items.append(("pagebreak",))
            prev_kind = None
            continue
        m = re.match(r'^(Q|C)(\d*)("([^"]*)")?\s*:(.*)$', line)
        if m:
            kind = m.group(1)
            numbered = bool(m.group(2))
            voice = int(m.group(2)) if numbered else 1
            name = m.group(4) or ""
            body = m.group(5)
            if kind == "Q":
                # 单声部行 ("Q:") 自成一行; 多声部行 ("Q1:","Q2:") 才合并成
                # 一个 system。已编号的声部行只有在前一行是歌词行、且编号回退
                # 时, 才开启新的 system (声部编号重新从 1 开始)。
                if qgroup:
                    if not numbered or not group_numbered:
                        flush_group()
                    elif (prev_kind == "C"
                          and voice <= max(v.voice for v in qgroup)):
                        flush_group()
                q = QLine(voice, name)
                raw = []
                for kind2, tok in tokenize(body):
                    if kind2 == "bar":
                        raw.append(parse_bar(tok))
                    elif kind2 == "block":
                        bkind, bels = parse_block(tok)
                        # 块从当前小节开始 (之前已结束的小节数)
                        m0 = len([e for e in raw if isinstance(e, BarEl)])
                        q.temps.append(TempBlock(bkind, m0, bels))
                    else:
                        raw.append(parse_note(tok))
                q.elements = merge_elements(raw)
                apply_tuplets(q.elements)
                for tb in q.temps:
                    apply_tuplets(tb.elements)
                qgroup.append(q)
                order.append(("Q", q))
                group_numbered = numbered
            else:
                lyric = LyricLine(voice, body)
                lyrics.append(lyric)
                order.append(("C", lyric))
            prev_kind = kind
            continue
        m2 = re.match(r"^([VBZDPJXH])\s*:\s*(.*)$", line)
        if m2:
            key, val = m2.group(1), m2.group(2).strip()
            if key == "V":
                header.version = val
            elif key == "B":
                header.titles.append(val)
            elif key == "Z":
                header.authors.append(val)
            elif key == "D":
                header.key, header.key_acc = parse_key(val)
            elif key == "P":
                header.pai, header.pai_aux = parse_pai(val)
            elif key == "J":
                header.tempo = val
                if re.match(r"^\d+$", val):
                    header.tempo_num = val
            elif key == "X":
                header.number = val
            elif key == "H":
                header.page = val
    flush_group()
    return header, items


