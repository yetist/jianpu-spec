    def _draw_curly(self, x, y, k, face=1, kind="temp", sy=1.0):
        """花括号 (直接用参考实现的填充字形)。

        kind="temp" 用 dakuohu_zuo_2 (临时多声部区间, 高 79px, 锚点在中心);
        kind="lyric" 用 ci_dakuohu_zuo (多行歌词组, 原高 14.77px, 按 sy 拉伸,
        锚点在中心)。face=-1 画右花括号 (横向镜像)。
        """
        if kind == "temp":
            d = CURLY_TEMP_D
            tr = ("translate(%.3f %.3f) scale(%.4f %.4f) translate(-50 -50)"
                  % (x, y, face * k, k))
        else:
            d = CURLY_LYRIC_D
            tr = ("translate(%.3f %.3f) scale(%.4f %.4f)"
                  % (x, y, face * k, sy * k))
        g = self.dwg.g(transform=tr)
        g.add(self.dwg.path(d=d, fill="#1b1b1b", stroke="none"))
        self.dwg.add(g)

    def _draw_voice_bracket(self, left, top, bottom, k):
        """多声部左侧括线: 粗 4px + 细 2px 两根竖线, 两端再用一条斜线把
        两根竖线连起来 (参考实现的 shengbufu_shang / shengbufu_xia 字形)。

        粗线在音符左 25.5px、上下各超出 6.5px; 细线在左 21px、上下各超出
        8px。斜线起于细线右上方, 向左下方落到粗线顶端, 下端镜像。"""
        for dx, over, w in ((25.5, 6.5, 4.0), (21.0, 8.0, 2.0)):
            x = left - dx * k
            self.line(x, top - over * k, x, bottom + over * k, w * k)
        spec = ((left - 17.9 * k, top - 13.0 * k, 5.5, 7.4),
                (left - 17.75 * k, bottom + 13.4 * k, -5.72, -7.7))
        for x0, y0, cy, ey in spec:
            d = "M %.2f %.2f C %.2f %.2f %.2f %.2f %.2f %.2f" % (
                x0, y0, x0, y0, x0 - k, y0 + cy * k, x0 - 9.4 * k,
                y0 + ey * k)
            self.dwg.add(self.dwg.path(d=d, fill="none", stroke="#1b1b1b",
                                       stroke_width="%.2fpx" % (2 * k)))

    # ---- 渐强 / 渐弱 --------------------------------------------------
    def _draw_hairpins(self, qline, idpos, nb):
        k = self.k
        start = None
        for el in qline.elements:
            if not isinstance(el, NoteEl):
                continue
            if el.cresc and start is None:
                start = el
            if el.cresc_end and start is not None:
                self._hairpin(start.cresc, idpos.get(id(start)),
                              idpos.get(id(el)), nb, k)
                start = None

    def _hairpin(self, cresc, a, b, nb, k):
        """渐强 (<) / 渐弱 (>) 楔形。

        参考实现用两条独立的开放式斜线 (从尖端出发), 右侧不封口; 范围从
        起音音符左边 7px 到收音音符右边 7px, 尖端在音符行上方 30px 处,
        开口半高 5px。
        """
        if a is None or b is None:
            return
        d, plus = cresc
        x1 = a[0] - 7 * k               # 起音音符左缘
        x2 = b[0] + 7 * k               # 收音音符右缘
        y = nb - (30 + plus * 7) * k
        sp = 5.0 * k
        if d == "<":
            ax, bx = x1, x2             # 尖端在左, 向右张开
        else:
            ax, bx = x2, x1             # 尖端在右, 向左张开
        self.line(ax, y, bx, y - sp, 1.0 * k)
        self.line(ax, y, bx, y + sp, 1.0 * k)

    # ---- 连音线 -------------------------------------------------------
    # 参考实现实测: 平连音线端点离音符行 16px; 高八度点 +5; 保持音 +2;
    # 延长音 +7; 音符同时有高八度点和记号时记号又高 3px。连音线要躲开
    # 起点/终点上最高的东西, 也要躲开跨过的音符 (跨过的高八度点让弧线
    # 再高 3px); 嵌套一层再 +8 (长连音线只 +4)。起止音符完全相同的第二
    # 条只错开 5px。
    TIE_MARK_OFF = {"bc": 2.0, "yc": 7.0}

    @staticmethod
    def _tie_obstacle(n):
        """音符上方记号/高八度点相对音符行的高度 (参考系 px)。"""
        off = 0.0
        for m in n.articulations:
            off = max(off, Renderer.TIE_MARK_OFF.get(m, 0.0))
        if n.octave > 0:
            return off + 5.0 + (3.0 if off else 0.0)
        return off

    @staticmethod
    def _tie_lift(level, first_obs, inside_obs):
        """连音线端点离音符行的高度 (参考系 px)。

        ``first_obs`` 是起点处 (未嵌套时还有终点) 最高的东西,
        ``inside_obs`` 是弧线跨过的音符上方最高的东西。
        """
        lift = 16.0 + 8.0 * level
        if level == 0:
            return lift + max(first_obs, inside_obs)
        # 嵌套时收尾处的记号不再计入, 起点照旧, 跨过的音符再高 3px
        return lift + max(first_obs, inside_obs + 3.0 if inside_obs else 0.0)

    @staticmethod
    def _tie_top(lift, multi):
        """连音线 (含弧顶, 必要时含线上数字) 在音符行上方的高度。"""
        h = lift + 10                      # 弧顶/平线高度
        if multi:
            h = max(h, lift + TUP_NUM_DY + TUP_NUM_H / 2.0)
        return h

    def _row_headroom(self, qline):
        """一个声部行自身内容在音符行上方能达到的最高高度 (参考系 px)。

        跳房子横线必须落在这些内容之上, 不能压到连音线/八度点/力度/渐强线。
        只统计确实会高过 HOUSE_PAD 的东西 (歌词、减时线都在行下方, 各种
        小记号最高约 22px, 参考实现也不会为它们抬高跳房子)。
        """
        top = 0.0
        for el in qline.elements:
            if not isinstance(el, NoteEl):
                continue
            if el.dynamics:
                top = max(top, 26 + SMALL * 0.78)      # 力度记号 (基线 -26)
            if el.octave > 0:                          # 高八度点
                top = max(top, OCT_HIGH + (el.octave - 1) * OCT_STEP)
            if el.cresc:                               # 渐强/渐弱线的上开口
                top = max(top, 30 + el.cresc[1] * 7 + 5)
        for _a, _b, lift, multi, _n, _lv in self._tie_specs(qline.elements):
            top = max(top, self._tie_top(lift, multi))
        return top

    @staticmethod
    def _tie_spec(a, b, level, count, inside=(), dup=False):
        # 音符上方若还有记号 (延长/保持) 或高八度点, 连音线要让开;
        # 包住别的连音线时也要更高
        oa = Renderer._tie_obstacle(a)
        ob = Renderer._tie_obstacle(b)
        oin = max([Renderer._tie_obstacle(n) for n in inside] or [0.0])
        first = max(oa, ob) if level == 0 else oa
        lift = Renderer._tie_lift(0 if dup else level, first, oin)
        if dup:                            # 起止相同的第二条: 只高 5px
            lift += 5.0
        return (a, b, lift, a.multi, count, 0 if dup else level)

    def _tie_specs(self, elements):
        """按开/闭顺序把音符配成连音线。

        返回 [(起点元素, 终点元素, 端点高度, 是否标数字, 连音包含的音符数,
        嵌套层数)]。绘制和纵向占位计算共用这套配对逻辑。参考实现遇到右
        括弧时收掉 *最早* 开的那条 (先开先闭), 因此 ``(1')`` 这种同时开、
        闭的写法表示 “收掉外层、另起一条”, 而不是一条只包一个音符的连音线。
        """
        specs = []
        stack = []                      # [序号, 起始元素]
        notes = []
        pairs = []
        for el in elements:
            if not isinstance(el, NoteEl):
                continue
            start = len(notes)
            notes.append(el)
            for _ in range(el.closes):
                if not stack:
                    break
                i, a = stack.pop(0)
                if i == start:
                    # 只包住一个音符的连音线 (如 (3)) 参考实现不画
                    continue
                pairs.append((i, start, a, el))
            for _ in range(el.opens):
                stack.append([start, el])
        # 连音(多连音)到行末还没遇到右括弧时, 参考实现在本行最后一个音符处
        # 收口, 数字就是本行里连起来的音符数 (跨行的部分在下一行另画弧线,
        # 不再重复写数字)。
        while stack:
            i, a = stack.pop(0)
            if a.multi and notes:
                pairs.append((i, len(notes) - 1, a, notes[-1]))
        # 嵌套层数按包含关系算 (参考实现: 包住别的连音线的那条更高),
        # 与右括弧的收束顺序无关。
        starts = {}
        for i, j, _a2, _b2 in pairs:
            starts[i] = starts.get(i, 0) + 1
        for i, j, a, b in pairs:
            inner = sum(1 for i2, j2, _a2, _b2 in pairs
                        if (i2, j2) != (i, j) and i <= i2 and j2 <= j)
            # 同一个音符上连开三层时参考实现只画两层
            if inner >= 2 and starts.get(i, 0) > 2:
                continue
            specs.append(self._tie_spec(a, b, inner, j - i + 1,
                                        notes[i + 1:j]))
        # 起止音符完全相同的两条连音线: 参考实现只错开 5px 画成两条,
        # 第三条开始不再画。
        seen = {}
        out = []
        for spec in specs:
            key = (id(spec[0]), id(spec[1]))
            n = seen.get(key, 0)
            seen[key] = n + 1
            if n >= 2:
                continue
            if n == 1:
                spec = self._tie_spec(spec[0], spec[1], 0, spec[4], dup=True)
            out.append(spec)
        return out

    @staticmethod
    def _tie_scan(elements, depth=0):
        """统计一行的连音线开闭情况 (用于跨行连音线)。

        返回 (行末仍未收口的条数, 行首第一个音符就收口的条数)。``depth`` 是
        从上一行带过来的未收口条数, 这些连音线只能被行首的右括弧收掉, 因为
        新的左括弧会压在上面 (后开先闭)。
        """
        lead = None
        for el in elements:
            if not isinstance(el, NoteEl):
                continue
            if lead is None:
                lead = min(depth, el.closes)
            depth += el.opens - el.closes
            if depth < 0:
                depth = 0
        return depth, (lead or 0)

    def _tie_carries(self, items):
        """按声部把各行的连音线开闭串起来, 得出跨行连音线的两端。

        参考实现遇到跨行的连音线时, 在行末画一段上扬的弧线, 在下一行行首
        画一段落到音符上的弧线 (连音/多连音同样处理)。只有真正在下一行行首
        收口的连音线才画, 源码里漏写右括弧的不画。
        """
        info = {}
        per_voice = {}
        for it in items:
            if it[0] != "system":
                continue
            for vi, q in enumerate(it[1]):
                per_voice.setdefault(vi, []).append(q)
        for qs in per_voice.values():
            prev_q = None
            prev_depth = 0
            for q in qs:
                depth, lead = self._tie_scan(q.elements, prev_depth)
                info[id(q)] = [min(prev_depth, lead), 0]
                if prev_q is not None:
                    info[id(prev_q)][1] = min(prev_depth, lead)
                prev_q, prev_depth = q, depth
        return info

    def _hook(self, x, y, k, left=True):
        """连音线两端的小钩 (参考实现 lianyinxian_zuo / lianyinxian_you)。

        字形从 (x+0.75, y+0.75) 出发, 向左 (或右) 下方落到离起点 11.5px、
        低 8.9px 处, 正好落在音符中心上方。
        """
        if left:
            d = ("M %.2f %.2f C %.2f %.2f %.2f %.2f %.2f %.2f"
                 % (x + 0.75 * k, y + 0.75 * k,
                    x + 0.75 * k, y + 0.75 * k,
                    x - 7.64 * k, y + 1.32 * k,
                    x - 11.47 * k, y + 9.63 * k))
        else:
            d = ("M %.2f %.2f C %.2f %.2f %.2f %.2f %.2f %.2f"
                 % (x + 0.75 * k, y + 0.75 * k,
                    x + 0.75 * k, y + 0.75 * k,
                    x + 8.39 * k, y + 1.32 * k,
                    x + 11.87 * k, y + 9.63 * k))
        self.dwg.add(self.dwg.path(d=d, fill="none", stroke="#1b1b1b",
                                   stroke_width="%.2fpx" % (1.2 * k),
                                   stroke_linecap="round"))

    @staticmethod
    def _tie_open_start(elements):
        """返回行末仍未收口的连音线的起始音符 (没有则 None)。"""
        stack = []
        for el in elements:
            if not isinstance(el, NoteEl):
                continue
            for _ in range(el.closes):
                if stack:
                    stack.pop(0)
            for _ in range(el.opens):
                stack.append(el)
        return stack[0] if stack else None

    def _draw_ties(self, elements, idpos, k, carry_in=0, carry_out=0,
                   right=None):
        for a, b, lift, multi, n, level in self._tie_specs(elements):
            if id(a) in idpos and id(b) in idpos:
                self._tie(idpos[id(a)], idpos[id(b)], lift,
                          multi, k, n, level)
        notes = [el for el in elements
                 if isinstance(el, NoteEl) and id(el) in idpos]
        if not notes:
            return
        if carry_in:
            # 行首: 只在左页边 (音符区左侧 12px) 画一个右钩, 钩尖正好落在
            # 第一个音符上方; 参考实现不画平线。
            el = notes[0]
            x, y = idpos[id(el)]
            lift = 16.0 + self._tie_obstacle(el)
            self._hook(MUSIC_L - 12 * k, y - (lift + HOOK_RISE) * k, k,
                       left=False)
        if carry_out:
            # 行末仍未收口的连音线: 参考实现把上扬钩画在它 *起头* 的音符
            # 处 (通常是本行最后一个音符, 但若最后一个音符只是收掉别的
            # 连音线, 钩子会落在更靠左的起点上)。
            el = self._tie_open_start(elements) or notes[-1]
            x, y = idpos.get(id(el), idpos[id(notes[-1])])
            lift = 16.0 + self._tie_obstacle(el)
            ay = y - (lift + HOOK_RISE) * k
            self._hook(x + HOOK_ANCHOR * k, ay, k, left=True)
            if right is not None and right > x + HOOK_ANCHOR * k:
                self.line(x + (HOOK_ANCHOR + 0.8) * k, ay + 0.75 * k, right,
                          ay + 0.75 * k, 1.2 * k)

    def _tie(self, a, b, lift, multi, k, count=2, level=0):
        x1, y1 = a
        x2, y2 = b
        y = min(y1, y2) - lift * k
        mid = (x1 + x2) / 2.0
        span = abs(x2 - x1)
        if multi or span <= TIE_FLAT_MIN * k:
            # 短连音线: 一条中间平、两端下垂的细弧。参考实现用一条 0.5px
            # 的路径来回画两遍 (回程低 1px), 看起来像一条略粗的扁弧。
            x1 += TIE_INSET * k
            x2 -= TIE_INSET * k
            span = abs(x2 - x1)
            d = 0.3 * span - 0.4 * k
            sgn = 1.0 if x2 > x1 else -1.0
            c1 = x1 + sgn * d
            c2 = x2 - sgn * d
            top = TIE_CTRL * k
            path = ("M %.2f %.2f C %.2f %.2f %.2f %.2f %.2f %.2f "
                    "M %.2f %.2f C %.2f %.2f %.2f %.2f %.2f %.2f") % (
                        x1, y, c1, y - top, c2, y - top, x2, y,
                        x2, y, c2, y - top + k, c1, y - top + k, x1, y)
            # 参考实现不写 fill, 两条方向相反的子路径之间那 1px 的缝隙
            # 会被填黑, 弧线因此比单纯 0.5px 描边略粗、两端更尖。
            self.dwg.add(self.dwg.path(d=path, stroke="#1b1b1b",
                                       stroke_width="%.2fpx" % (0.5 * k)))
        else:
            # 长连音线: 一条平线加两端小钩 (参考实现 lianyinxian_* 字形)。
            # 平线比弧线低, 嵌套一层只抬高 4px。
            ay = y + 4.0 * level * k - HOOK_RISE * k
            self._hook(x1 + HOOK_ANCHOR * k, ay, k, left=True)
            self._hook(x2 - HOOK_ANCHOR * k, ay, k, left=False)
            self.line(x1 + (HOOK_ANCHOR + 0.8) * k, ay + 0.75 * k,
                      x2 - (HOOK_ANCHOR - 1.0) * k, ay + 0.75 * k, 1.2 * k)
        if multi:
            # 连音数字: 写在本行音符数上, 位于弧线中点上方 (参考实现用一个
            # 带白底的小号数字把弧线遮出一个缺口)。
            ny = y - TUP_NUM_DY * k
            self.dwg.add(self.dwg.rect(
                insert=(mid - TUP_NUM_W * k / 2.0,
                        ny - TUP_NUM_H * k / 2.0),
                size=(TUP_NUM_W * k, TUP_NUM_H * k), fill="#ffffff"))
            self.text(str(count), mid, ny + 4.0 * k, 11 * k,
                      family=FONT_NOTE, weight="bold")

    # ---- 跳房子 -------------------------------------------------------
    def _draw_houses(self, qlines, mstart, mend, nmeas, y):
        """绘制跳房子 (反复跳跃记号)。

        横线高度由调用方按"音符行上方内容 + HOUSE_CLEAR"算好 (house_off),
        两端竖线下垂 HOUSE_TICK, 房号写在横线下方、左端稍右处。

        相邻两个跳房子共用一个端点 (前一个的终点小节线就是后一个的起点)
        时, 两根竖线各向自己一侧让出 HOUSE_GAP/2, 避免叠在一条线上。
        """
        k = self.k
        half = HOUSE_GAP * k / 2.0      # 相邻跳房子各让出的间隙
        open_bar = None
        xa = 0.0
        last_end = None                 # 上一个跳房子终点所用的小节线位置
        for m in range(nmeas):
            bar = None
            for q in qlines:
                mm = q.measures
                if m < len(mm) and mm[m][1] is not None:
                    bar = mm[m][1]
                    break
            if bar is None:
                continue
            # 先结束上一个跳房子, 再开启新的 (同一小节线可能既是终点又是起点)
            if bar.house_close and open_bar is not None:
                xb = mend[m + 1]
                # 本条小节线上紧接着还要开启下一个跳房子 -> 终点左移
                xe = xb - (half if bar.house_open else 0.0)
                self.line(xa, y, xe, y, 1.2 * k)
                self.line(xa, y, xa, y + HOUSE_TICK * k, 1.2 * k)
                if not (bar.house_unclosed or open_bar.house_unclosed):
                    self.line(xe, y, xe, y + HOUSE_TICK * k, 1.2 * k)
                if open_bar.house_text:
                    self.text(open_bar.house_text, xa + 3 * k,
                              y + (HOUSE_TICK + 6) * k, SMALL * k,
                              anchor="start", family=FONT_SANS)
                open_bar = None
                last_end = xb
            if bar.house_open:
                open_bar = bar
                x0 = mend[m + 1]
                # 上一个跳房子刚在同一个位置结束 -> 起点右移, 两根竖线分开
                if last_end is not None and abs(x0 - last_end) < 1.0:
                    x0 += half
                xa = x0


