def _is_house_start(s, i):
    j = i + 1
    n = len(s)
    while j < n and s[j] in "+/":
        j += 1
    return j < n and s[j] == '"'


def _is_bar_paren(s, i):
    j = i
    n = len(s)
    while j < n and (s[j] == "(" or s[j] == " "):
        j += 1
    return j < n and s[j] in "|:"


def _scan_bar(s, i):
    n = len(s)
    j = i
    buf = ""
    while j < n:
        c = s[j]
        if c in "|:":
            buf += c
            j += 1
            continue
        if c == "/":
            if buf and buf[-1] in "|]":
                buf += "/"
                j += 1
                continue
            break
        if c in "*+":
            buf += c
            j += 1
            continue
        if c == "&":
            k = j + 1
            while k < n and s[k].isalpha():
                k += 1
            buf += s[j:k]
            j = k
            continue
        if c == "]":
            buf += c
            j += 1
            continue
        if c == "[":
            if _is_house_start(s, j):
                buf += c
                j += 1
                continue
            break
        if c == '"':
            k = s.find('"', j + 1)
            if k < 0:
                k = n - 1
            buf += s[j:k + 1]
            j = k + 1
            continue
        if c == "(" and not buf:
            buf += "("
            j += 1
            continue
        break
    return buf, j


def tokenize(s):
    """返回 [(kind, text), ...], kind 为 'note' / 'bar' / 'block'。"""
    tokens = []
    cur = ""
    cur_has = False
    i = 0
    n = len(s)
    quote = False
    grace = 0

    def flush():
        nonlocal cur, cur_has
        if cur:
            tokens.append(("note", cur))
            cur = ""
            cur_has = False

    while i < n:
        c = s[i]
        if quote:
            cur += c
            if c == '"':
                quote = False
            i += 1
            continue
        if grace > 0:
            cur += c
            if c == "[":
                grace += 1
            elif c == "]":
                grace -= 1
            i += 1
            continue
        if c in " \t":
            flush()
            i += 1
            continue
        if c in "|:":
            flush()
            tok, i = _scan_bar(s, i)
            tokens.append(("bar", tok))
            continue
        if c == "[" and _is_house_start(s, i):
            flush()
            tok, i = _scan_bar(s, i)
            tokens.append(("bar", tok))
            continue
        if c == "(" and _is_bar_paren(s, i):
            flush()
            tok, i = _scan_bar(s, i)
            tokens.append(("bar", tok))
            continue
        if c == "{":
            flush()
            j = s.find("}", i)
            if j < 0:
                j = n - 1
            tokens.append(("block", s[i:j + 1]))
            i = j + 1
            continue
        if c == "}":
            i += 1
            continue
        if c == '"':
            quote = True
            cur += c
            i += 1
            continue
        if c == "[":
            grace = 1
            cur += c
            i += 1
            continue
        if c.isdigit() or c == "-":
            if cur_has and c != "~":
                flush()
            cur_has = True
            cur += c
            i += 1
            continue
        cur += c
        i += 1
    flush()
    return tokens


